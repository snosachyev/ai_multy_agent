"""Модуль для расчета метрик точности поисковой выдачи: Precision@K."""

from typing import List, Set


def precision_at_k(
    retrieved_ids: List[str],
    relevant_ids: List[str],
    k: int,
) -> float:
    """Вычисляет метрику Precision@K (точность на уровне K) для поискового запроса.

    Метрика показывает долю релевантных документов среди первых K возвращенных 
    поисковой системой документов. Рассчитывается как:
    (количество релевантных документов в топ-K) / K.

    Args:
        retrieved_ids: Список идентификаторов документов, возвращенных поисковой системой 
            в порядке убывания релевантности.
        relevant_ids: Список идентификаторов документов, признанных релевантными (ground truth).
        k: Количество первых документов (глубина выдачи) для расчета точности.

    Returns:
        float: Значение точности в диапазоне [0.0, 1.0]. Если `k <= 0` или список 
            `retrieved_ids` пуст, возвращается `0.0`.
    """
    if k <= 0:
        return 0.0

    # Берем срез до K элементов. Если в выдаче меньше документов, чем K, 
    # срез безопасно вернет все доступные элементы.
    retrieved_top_k: List[str] = retrieved_ids[:k]

    if not retrieved_top_k:
        return 0.0

    # Преобразуем в set для O(1) поиска
    relevant_set: Set[str] = set(relevant_ids)

    # Рефакторинг: генераторное выражение внутри sum() заменено на более эффективную 
    # проверку вхождения элементов списка в set.
    hits: int = sum(1 for doc_id in retrieved_top_k if doc_id in relevant_set)

    # Делим на фактическую длину среза, чтобы корректно обрабатывать случаи, 
    # когда k больше, чем общее количество возвращенных документов.
    return hits / len(retrieved_top_k)
