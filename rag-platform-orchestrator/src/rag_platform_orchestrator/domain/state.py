"""Модуль langraph стэйт"""
from typing import Literal, Optional, TypedDict
from langchain_core.messages import BaseMessage


class AgentResult(TypedDict):
    """Agent result Dict"""
    agent: str
    task: str
    result: str
    success: bool
    error: str | None


class AgentState(TypedDict):
    """Класс langraph стэйт"""
    # --------------------------------------------------------
    # Основной запрос пользователя
    # --------------------------------------------------------

    user_input: str

    # --------------------------------------------------------
    # История сообщений
    # --------------------------------------------------------

    messages: list[BaseMessage]

    # --------------------------------------------------------
    # Workflow
    # --------------------------------------------------------

    workflow_id: str

    current_agent: Optional[str]

    # Конкретная задача, которую Director
    # поставил текущему агенту
    current_task: Optional[str]

    next_action: Literal[
        "researcher",
        "analyst",
        "finish"
    ]

    # --------------------------------------------------------
    # Защита от бесконечных циклов
    # --------------------------------------------------------

    iteration: int
    max_iterations: int

    # --------------------------------------------------------
    # Результаты агентов
    # --------------------------------------------------------

    research_result: Optional[str]

    analysis_result: Optional[str]

    # --------------------------------------------------------
    # История выполнения
    # --------------------------------------------------------

    agent_results: list[AgentResult]

    # Задачи, которые уже были успешно выполнены
    completed_tasks: list[str]

    # --------------------------------------------------------
    # Последнее действие
    # --------------------------------------------------------

    last_action: Optional[str]

    last_agent_success: Optional[bool]

    last_error: Optional[str]

    # --------------------------------------------------------
    # Ошибки
    # --------------------------------------------------------

    errors: list[str]

    # --------------------------------------------------------
    # Финальный ответ
    # --------------------------------------------------------

    final_answer: Optional[str]
