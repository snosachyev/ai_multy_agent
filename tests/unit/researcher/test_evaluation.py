"""Модульные тесты для проверки функции агрегации и вычисления 
среднего значения метрик (average)."""

from evaluation.researcher.metrics import average


def test_average_numeric_metrics():
    """Проверяет корректность расчета среднего значения для простых числовых метрик.

    Тест контролирует, что для плоского списка значений (например, recall_at_k)
    вычисляется правильное среднее арифметическое.
    """
    results = [
        {"recall_at_k": 0.8},
        {"recall_at_k": 0.6},
    ]

    assert average(results, "recall_at_k") == 0.7


def test_average_generation_metrics():
    """Проверяет расчет среднего значения для вложенных структур метрик генерации.

    Тест гарантирует, что функция умеет извлекать данные из комплексных объектов
    метрик, где числовая оценка находится во вложенном поле {"score": value}.
    """
    results = [
        {"faithfulness": {"score": 1.0}},
        {"faithfulness": {"score": 0.5}},
    ]

    assert average(results, "faithfulness") == 0.75


def test_average_empty_results():
    """Проверяет безопасную обработку пустого списка результатов.

    Тест контролирует, что передача пустого списка не приводит к ошибке ZeroDivisionError,
    а возвращает дефолтное значение 0.0.
    """
    assert average([], "recall_at_k") == 0.0


def test_average_missing_metric():
    """Проверяет устойчивость функции к отсутствию запрашиваемой метрики в части словарей.

    Тест гарантирует, что если в некоторых элементах списка нужный ключ отсутствует
    или словарь пуст, функция корректно рассчитывает среднее только по тем элементам,
    где данная метрика присутствует.
    """
    results = [
        {"recall_at_k": 0.8},
        {"other_metric": 0.5},
        {},
    ]

    assert average(results, "recall_at_k") == 0.8
