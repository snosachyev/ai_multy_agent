"""Модуль для расчета метрик полноты поисковой выдачи: Recall@K."""

from typing import List, Set


def recall_at_k(
    retrieved_ids: List[str],
    relevant_ids: List[str],
    k: int,
) -> float:
    """Вычисляет метрику Recall@K (полнота на уровне K) для поискового запроса.

    Метрика показывает, какую долю от всех истинно релевантных документов 
    поисковая система смогла найти в первых K элементах выдачи. 
    Рассчитывается как: 
        (количество найденных релевантных документов в топ-K) / (всего релевантных документов).

    Args:
        retrieved_ids: Список идентификаторов документов, возвращенных поисковой системой 
            в порядке убывания релевантности.
        relevant_ids: Список идентификаторов документов, признанных релевантными (ground truth).
        k: Количество первых документов (глубина выдачи) для расчета полноты.

    Returns:
        float: Значение полноты в диапазоне [0.0, 1.0]. Если список `relevant_ids` пуст 
            или `k <= 0`, возвращается `0.0`.
    """
    if k <= 0:
        return 0.0

    if not relevant_ids:
        return 0.0

    # Рефакторинг: для оптимизации сначала преобразуем переданные релевантные ID в set.
    relevant_set: Set[str] = set(relevant_ids)
    
    # Вместо создания большого set(retrieved_ids[:k]) эффективнее посчитать совпадения в цикле, 
    # так как срез retrieved_ids[:k] содержит только уникальные ID документов от поисковика.
    retrieved_top_k: List[str] = retrieved_ids[:k]
    
    hits: int = sum(1 for doc_id in retrieved_top_k if doc_id in relevant_set)

    return hits / len(relevant_set)
